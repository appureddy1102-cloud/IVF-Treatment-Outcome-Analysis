import os
import numpy as np
import pandas as pd

SEED = 42


def sigmoid(x):
    return 1.0 / (1.0 + np.exp(-x))


def generate_all_datasets(output_dir: str = "data/raw", seed: int = SEED):
    os.makedirs(output_dir, exist_ok=True)
    rng = np.random.default_rng(seed)

    # =========================================================================
    # 1. GENERATE PATIENTS (Base: 3,900 unique synthetic patients)
    # =========================================================================
    n_patients = 3900
    patient_ids = np.array([f"PT-{10001 + i}" for i in range(n_patients)])

    # Maternal Age: realistic clinic distribution (22 to 45 years, mean ~34.0)
    ages = np.round(rng.normal(loc=34.0, scale=4.6, size=n_patients), 0).astype(float)
    ages = np.clip(ages, 22, 45)

    # Medical History Category (diagnosis probabilities vary mildly with age)
    med_categories = [
        "Male Factor",
        "Ovulatory Dysfunction / PCOS",
        "Tubal Factor",
        "Unexplained Infertility",
        "Endometriosis",
        "Diminished Ovarian Reserve",
        "Uterine Factor",
    ]
    med_history = []
    for a in ages:
        if a >= 39:
            probs = [0.20, 0.08, 0.12, 0.18, 0.09, 0.27, 0.06]
        elif a <= 29:
            probs = [0.27, 0.24, 0.14, 0.17, 0.11, 0.03, 0.04]
        else:
            probs = [0.25, 0.16, 0.14, 0.19, 0.11, 0.10, 0.05]
        med_history.append(rng.choice(med_categories, p=probs))
    med_history = np.array(med_history)

    # BMI (kg/m^2): realistic right-skewed distribution, slightly higher in PCOS
    bmi_base = rng.lognormal(mean=np.log(24.4), sigma=0.17, size=n_patients)
    pcos_shift = np.where(med_history == "Ovulatory Dysfunction / PCOS", rng.normal(2.1, 1.2, n_patients), 0.0)
    bmi = np.round(np.clip(bmi_base + pcos_shift, 17.4, 42.5), 1)

    # Infertility Duration (Years): 0.5 to 14.0, mildly correlated with age
    inf_dur = np.round(
        np.clip(rng.gamma(shape=2.3, scale=1.35, size=n_patients) + (ages - 30) * 0.08, 0.5, 14.5),
        1,
    )

    # Infertility Type: Primary (~64%) vs Secondary (~36%), older slightly more Secondary
    sec_prob = np.clip(0.26 + (ages - 28) * 0.012, 0.18, 0.52)
    inf_type = np.where(rng.random(n_patients) < sec_prob, "Secondary", "Primary")

    # Previous IVF Attempts: 0 to 5
    lam_prev = np.clip(0.35 + (ages - 28) * 0.035 + inf_dur * 0.06, 0.15, 2.0)
    prev_attempts = np.clip(rng.poisson(lam=lam_prev), 0, 5)

    # AMH Level (ng/mL): physiologically declines with age, elevated in PCOS, low in DOR
    log_amh = (
        1.25
        - 0.048 * (ages - 30)
        + np.where(med_history == "Ovulatory Dysfunction / PCOS", 0.62, 0.0)
        + np.where(med_history == "Diminished Ovarian Reserve", -0.88, 0.0)
        + rng.normal(0, 0.42, n_patients)
    )
    amh = np.round(np.clip(np.exp(log_amh), 0.12, 11.50), 2)

    # Basal FSH Level (mIU/mL): inversely associated with AMH + substantial biological noise
    fsh = np.round(
        np.clip(9.8 - 1.45 * np.log(amh + 0.3) + 0.09 * (ages - 32) + rng.normal(0, 1.85, n_patients), 2.8, 22.4),
        2,
    )

    patients_clean_ref = pd.DataFrame({
        "Patient_ID": patient_ids,
        "Age": ages,
        "BMI": bmi,
        "Infertility_Duration_Years": inf_dur,
        "Infertility_Type": inf_type,
        "Previous_IVF_Attempts": prev_attempts,
        "AMH_Level": amh,
        "FSH_Level": fsh,
        "Medical_History_Category": med_history,
    })

    # Map patient attributes for cycle generation before injecting raw dirtiness
    pt_lookup = patients_clean_ref.set_index("Patient_ID").to_dict(orient="index")

    # =========================================================================
    # 2. GENERATE IVF TREATMENT CYCLES (Base: 5,320 cycles across 3,900 patients)
    # =========================================================================
    n_cycles = 5320
    # Ensure every patient has at least 1 cycle, remaining 1,420 cycles distributed across repeat patients
    extra_patient_ids = rng.choice(patient_ids, size=n_cycles - n_patients, replace=True)
    cycle_patient_ids = np.concatenate([patient_ids, extra_patient_ids])
    rng.shuffle(cycle_patient_ids)

    cycle_ids = np.array([f"CYC-{200001 + i}" for i in range(n_cycles)])

    # Treatment dates across 2023-01-01 to 2025-12-31
    start_ts = pd.Timestamp("2023-01-01").value // 10**9
    end_ts = pd.Timestamp("2025-12-31").value // 10**9
    rand_ts = np.sort(rng.integers(start_ts, end_ts, size=n_cycles))
    treatment_dates = pd.to_datetime(rand_ts, unit="s").strftime("%Y-%m-%d").to_numpy()

    treatment_types = []
    stim_protocols = []
    fert_methods = []
    retrieved_oocytes = []
    mature_oocytes = []
    fertilized_oocytes = []
    num_embryos = []
    num_transferred = []
    transfer_types = []

    for pid in cycle_patient_ids:
        p = pt_lookup[pid]
        p_age = p["Age"]
        p_amh = p["AMH_Level"]
        p_med = p["Medical_History_Category"]
        p_prev = p["Previous_IVF_Attempts"]

        # Treatment Type selection
        if p_med == "Male Factor":
            tt_probs = [0.10, 0.68, 0.16, 0.06]
        elif p_age >= 38 or p_prev >= 2:
            tt_probs = [0.22, 0.38, 0.30, 0.10]
        else:
            tt_probs = [0.38, 0.38, 0.15, 0.09]
        tt = rng.choice(
            ["Conventional IVF", "ICSI", "IVF + PGT-A", "Mild Stimulation IVF"],
            p=tt_probs,
        )
        treatment_types.append(tt)

        # Stimulation Protocol
        if tt == "Mild Stimulation IVF":
            sp = "Mild / Minimal Stimulation"
        elif p_med == "Ovulatory Dysfunction / PCOS" or p_amh > 4.0:
            sp = rng.choice(
                ["GnRH Antagonist", "GnRH Agonist Long", "Flare-Up Protocol"],
                p=[0.78, 0.17, 0.05],
            )
        elif p_med == "Diminished Ovarian Reserve" or p_amh < 1.0:
            sp = rng.choice(
                ["GnRH Antagonist", "GnRH Agonist Long", "Flare-Up Protocol", "Mild / Minimal Stimulation"],
                p=[0.50, 0.15, 0.23, 0.12],
            )
        else:
            sp = rng.choice(
                ["GnRH Antagonist", "GnRH Agonist Long", "Flare-Up Protocol", "Mild / Minimal Stimulation"],
                p=[0.58, 0.30, 0.06, 0.06],
            )
        stim_protocols.append(sp)

        # Fertilization Method aligned with Treatment Type
        if tt == "ICSI":
            fm = "ICSI"
        elif tt == "IVF + PGT-A":
            fm = rng.choice(["ICSI", "Split IVF-ICSI"], p=[0.82, 0.18])
        elif tt == "Conventional IVF":
            fm = rng.choice(["Conventional Insemination", "Split IVF-ICSI"], p=[0.85, 0.15])
        else:
            fm = rng.choice(["Conventional Insemination", "ICSI"], p=[0.55, 0.45])
        fert_methods.append(fm)

        # Retrieved Oocytes: Poisson-Gamma (NegBin-like) driven by AMH, Age, Protocol
        proto_mult = 0.65 if sp == "Mild / Minimal Stimulation" else (1.06 if sp == "GnRH Agonist Long" else 1.0)
        expected_ooc = (5.2 + 2.45 * np.sqrt(p_amh) - 0.18 * max(0, p_age - 31)) * proto_mult
        expected_ooc = np.clip(expected_ooc * rng.lognormal(0, 0.24), 1.5, 28.0)
        ret = int(np.clip(rng.poisson(expected_ooc), 1, 34))
        retrieved_oocytes.append(ret)

        # Mature Oocytes (MII): Binomial subset of Retrieved (~78% mean)
        mat_rate = np.clip(rng.normal(0.785 - 0.003 * max(0, p_age - 35), 0.08), 0.45, 0.96)
        mat = int(rng.binomial(ret, mat_rate))
        mature_oocytes.append(mat)

        # Fertilized Oocytes (2PN): Binomial subset of Mature (~74% mean; ICSI slightly higher in Male Factor)
        fert_base = 0.755 if fm == "ICSI" else (0.66 if p_med == "Male Factor" else 0.725)
        fert_rate = np.clip(rng.normal(fert_base, 0.09), 0.35, 0.95)
        fert = int(rng.binomial(mat, fert_rate))
        fertilized_oocytes.append(fert)

        # Number of Viable Embryos: Binomial subset of Fertilized (~61% mean)
        emb_rate = np.clip(rng.normal(0.63 - 0.008 * max(0, p_age - 34), 0.10), 0.25, 0.90)
        n_emb = int(rng.binomial(fert, emb_rate))
        num_embryos.append(n_emb)

        # Number of Embryos Transferred & Transfer Type
        if n_emb == 0:
            n_trans = 0
            tr_type = "No Transfer"
        else:
            # Small chance of freeze-all without immediate transfer / cycle cancellation (~4.5%, higher in OHSS risk)
            cancel_prob = 0.085 if ret >= 22 else 0.035
            if rng.random() < cancel_prob:
                n_trans = 0
                tr_type = "No Transfer"
            else:
                if tt == "IVF + PGT-A":
                    # PGT-A cycles predominantly Frozen-Thawed eSET
                    tr_type = rng.choice(["Frozen-Thawed Transfer", "Fresh Transfer"], p=[0.88, 0.12])
                    max_t = min(n_emb, 2)
                    n_trans = 1 if max_t == 1 else int(rng.choice([1, 2], p=[0.82, 0.18]))
                else:
                    tr_type = rng.choice(["Fresh Transfer", "Frozen-Thawed Transfer"], p=[0.54, 0.46])
                    if n_emb == 1:
                        n_trans = 1
                    elif n_emb == 2:
                        p_two = 0.42 if p_age >= 37 else 0.28
                        n_trans = int(rng.choice([1, 2], p=[1 - p_two, p_two]))
                    else:
                        if p_age >= 39:
                            n_trans = int(rng.choice([1, 2, 3], p=[0.48, 0.41, 0.11]))
                        else:
                            n_trans = int(rng.choice([1, 2, 3], p=[0.66, 0.31, 0.03]))
        num_transferred.append(n_trans)
        transfer_types.append(tr_type)

    cycles_clean_ref = pd.DataFrame({
        "Cycle_ID": cycle_ids,
        "Patient_ID": cycle_patient_ids,
        "Treatment_Date": treatment_dates,
        "Treatment_Type": treatment_types,
        "Stimulation_Protocol": stim_protocols,
        "Retrieved_Oocytes": retrieved_oocytes,
        "Mature_Oocytes": mature_oocytes,
        "Fertilized_Oocytes": fertilized_oocytes,
        "Fertilization_Method": fert_methods,
        "Number_of_Embryos": num_embryos,
        "Number_of_Embryos_Transferred": num_transferred,
        "Transfer_Type": transfer_types,
    })

    # =========================================================================
    # 3. GENERATE EMBRYO GRADING (One row per viable embryo in each cycle)
    # =========================================================================
    embryo_rows = []
    best_cycle_embryo_info = {}  # Cycle_ID -> summary of best cohort embryo for outcome simulation
    emb_counter = 1

    quality_rank_map = {"Excellent": 4, "Good": 3, "Fair": 2, "Poor": 1}

    for row in cycles_clean_ref.itertuples(index=False):
        cid = row.Cycle_ID
        n_emb = row.Number_of_Embryos
        p = pt_lookup[row.Patient_ID]
        p_age = p["Age"]
        tt = row.Treatment_Type

        if n_emb == 0:
            best_cycle_embryo_info[cid] = {
                "best_quality": "None",
                "best_day": "None",
                "best_rank": 0,
            }
            continue

        # Decide culture day strategy for the cycle cohort: Day 5 (~74%; 95% if PGT-A) vs Day 3 (~26%)
        if tt == "IVF + PGT-A":
            emb_day = "Day 5"
        elif n_emb <= 2 and p_age >= 37:
            emb_day = rng.choice(["Day 3", "Day 5"], p=[0.52, 0.48])
        else:
            emb_day = rng.choice(["Day 5", "Day 3"], p=[0.76, 0.24])

        cohort_records = []
        for _ in range(n_emb):
            eid = f"EMB-{300000 + emb_counter}"
            emb_counter += 1

            # Latent embryo developmental potential (noisy, mildly lower at advanced maternal age)
            latent_q = rng.normal(loc=0.18 - 0.032 * max(0, p_age - 33), scale=0.95)

            if emb_day == "Day 5":
                # Expansion Grade 1 to 6
                if latent_q > 0.85:
                    exp_g = str(rng.choice([4, 5, 6], p=[0.58, 0.32, 0.10]))
                    icm = rng.choice(["A", "B"], p=[0.74, 0.26])
                    te = rng.choice(["A", "B"], p=[0.70, 0.30])
                elif latent_q > -0.10:
                    exp_g = str(rng.choice([3, 4, 5], p=[0.38, 0.48, 0.14]))
                    icm = rng.choice(["A", "B", "C"], p=[0.32, 0.56, 0.12])
                    te = rng.choice(["A", "B", "C"], p=[0.28, 0.58, 0.14])
                elif latent_q > -0.90:
                    exp_g = str(rng.choice([2, 3, 4], p=[0.34, 0.46, 0.20]))
                    icm = rng.choice(["B", "C", "A"], p=[0.52, 0.38, 0.10])
                    te = rng.choice(["B", "C", "A"], p=[0.50, 0.42, 0.08])
                else:
                    exp_g = str(rng.choice([1, 2, 3], p=[0.38, 0.44, 0.18]))
                    icm = rng.choice(["C", "B"], p=[0.68, 0.32])
                    te = rng.choice(["C", "B"], p=[0.72, 0.28])

                stage_map = {
                    "1": "Early Blastocyst",
                    "2": "Early Blastocyst",
                    "3": "Full Blastocyst",
                    "4": "Expanded Blastocyst",
                    "5": "Hatching Blastocyst",
                    "6": "Hatched Blastocyst",
                }
                stage = stage_map[exp_g]
                morph = f"{exp_g}{icm}{te}"

                # Quality Category from Gardner Grade
                exp_num = int(exp_g)
                if exp_num >= 4 and icm == "A" and te == "A":
                    q_cat = "Excellent"
                elif exp_num >= 3 and icm in ("A", "B") and te in ("A", "B") and not (exp_num == 3 and icm == "B" and te == "B" and latent_q < -0.2):
                    q_cat = "Good" if not (exp_num >= 5 and (icm == "A" or te == "A") and icm != "C" and te != "C") else "Excellent"
                elif icm == "C" and te == "C" or exp_num == 1:
                    q_cat = "Poor"
                else:
                    q_cat = "Fair"
            else:
                # Day 3 Cleavage-Stage Grading
                exp_g = "Not Applicable"
                icm = "Not Applicable"
                te = "Not Applicable"
                if latent_q > 0.80:
                    stage = "Cleavage (8-Cell Symmetric)"
                    morph = "D3-8G1"
                    q_cat = "Excellent"
                elif latent_q > -0.10:
                    stage = "Cleavage (6-8 Cell)"
                    morph = rng.choice(["D3-8G2", "D3-7G1"], p=[0.6, 0.4])
                    q_cat = "Good"
                elif latent_q > -0.85:
                    stage = rng.choice(["Cleavage (6-8 Cell)", "Compacting Morula"], p=[0.75, 0.25])
                    morph = "D3-6G2"
                    q_cat = "Fair"
                else:
                    stage = "Cleavage (<6 Cell / Fragmented)"
                    morph = "D3-5G3"
                    q_cat = "Poor"

            rec = {
                "Embryo_ID": eid,
                "Cycle_ID": cid,
                "Embryo_Day": emb_day,
                "Embryo_Stage": stage,
                "Expansion_Grade": exp_g,
                "Inner_Cell_Mass_Grade": icm,
                "Trophectoderm_Grade": te,
                "Embryo_Quality_Category": q_cat,
                "Morphological_Grade": morph,
            }
            cohort_records.append(rec)
            embryo_rows.append(rec)

        # Best embryo in cohort (selected for transfer if transfer occurred)
        best_rec = max(cohort_records, key=lambda r: quality_rank_map[r["Embryo_Quality_Category"]])
        best_cycle_embryo_info[cid] = {
            "best_quality": best_rec["Embryo_Quality_Category"],
            "best_day": best_rec["Embryo_Day"],
            "best_rank": quality_rank_map[best_rec["Embryo_Quality_Category"]],
        }

    embryo_clean_ref = pd.DataFrame(embryo_rows)

    # =========================================================================
    # 4. GENERATE IMPLANTATION OUTCOMES (Consistent Clinical Cascade)
    # =========================================================================
    outcome_rows = []
    for idx, row in enumerate(cycles_clean_ref.itertuples(index=False)):
        oid = f"OUT-{400001 + idx}"
        cid = row.Cycle_ID
        n_trans = row.Number_of_Embryos_Transferred
        p = pt_lookup[row.Patient_ID]
        p_age = p["Age"]
        p_bmi = p["BMI"]
        p_prev = p["Previous_IVF_Attempts"]
        tt = row.Treatment_Type
        tr_type = row.Transfer_Type
        emb_info = best_cycle_embryo_info[cid]

        if n_trans == 0 or tr_type == "No Transfer":
            outcome_rows.append({
                "Outcome_ID": oid,
                "Cycle_ID": cid,
                "Implantation_Status": "No Transfer",
                "Pregnancy_Test_Result": "Not Applicable",
                "Clinical_Pregnancy_Status": "No",
                "Live_Birth_Status": "No",
                "Follow_Up_Status": "Completed",
            })
            continue

        # Probabilistic logistic model with realistic clinical noise (AUC ~0.66-0.70, not deterministic!)
        q_effect = {
            "Excellent": 0.56,
            "Good": 0.22,
            "Fair": -0.26,
            "Poor": -0.78,
        }.get(emb_info["best_quality"], -0.3)

        day_effect = 0.24 if emb_info["best_day"] == "Day 5" else -0.12
        age_effect = -0.045 * max(0, p_age - 31) - 0.055 * max(0, p_age - 37)
        pgta_effect = 0.22 if tt == "IVF + PGT-A" else 0.0
        fet_effect = 0.10 if tr_type == "Frozen-Thawed Transfer" else 0.0
        multi_transfer_effect = 0.20 if n_trans >= 2 else 0.0
        bmi_effect = -0.16 if (p_bmi >= 33.0 or p_bmi < 18.5) else 0.0
        prev_effect = -0.05 * min(p_prev, 4)
        noise = rng.normal(0, 0.35)

        # Positive Beta-hCG probability
        logit_hcg = -0.12 + q_effect + day_effect + age_effect + pgta_effect + fet_effect + multi_transfer_effect + bmi_effect + prev_effect + noise
        p_hcg = np.clip(sigmoid(logit_hcg), 0.06, 0.78)
        pos_hcg = rng.random() < p_hcg

        if not pos_hcg:
            preg_test = "Negative"
            imp_status = "Not Implanted"
            clin_preg = "No"
            live_birth = "No"
            follow_up = rng.choice(["Completed", "Lost to Follow-Up"], p=[0.985, 0.015])
        else:
            preg_test = "Positive"
            # ~87% of positive hCG achieve ultrasound-confirmed implantation (13% biochemical loss)
            p_imp_given_hcg = np.clip(0.88 - 0.008 * max(0, p_age - 35), 0.72, 0.93)
            implanted = rng.random() < p_imp_given_hcg
            if not implanted:
                imp_status = "Not Implanted"
                clin_preg = "No"
                live_birth = "No"
                follow_up = "Completed"
            else:
                imp_status = "Implanted"
                # ~91% of implanted sacs progress to clinical pregnancy with fetal cardiac activity
                p_clin_given_imp = np.clip(0.92 - 0.009 * max(0, p_age - 35), 0.76, 0.96)
                is_clin = rng.random() < p_clin_given_imp
                if not is_clin:
                    clin_preg = "No"
                    live_birth = "No"
                    follow_up = "Completed"
                else:
                    clin_preg = "Yes"
                    # Live birth given clinical pregnancy (~84% younger, declines with maternal age, higher in PGT-A)
                    p_lb_given_clin = np.clip(
                        0.855 - 0.016 * max(0, p_age - 34) + (0.04 if tt == "IVF + PGT-A" else 0.0),
                        0.55,
                        0.92,
                    )
                    is_lb = rng.random() < p_lb_given_clin
                    if is_lb:
                        live_birth = "Yes"
                        follow_up = "Completed"
                    else:
                        live_birth = "No"
                        follow_up = rng.choice(["Completed", "Ongoing Follow-Up", "Lost to Follow-Up"], p=[0.90, 0.06, 0.04])

        outcome_rows.append({
            "Outcome_ID": oid,
            "Cycle_ID": cid,
            "Implantation_Status": imp_status,
            "Pregnancy_Test_Result": preg_test,
            "Clinical_Pregnancy_Status": clin_preg,
            "Live_Birth_Status": live_birth,
            "Follow_Up_Status": follow_up,
        })

    outcomes_clean_ref = pd.DataFrame(outcome_rows)

    # =========================================================================
    # 5. GENERATE TREATMENT COSTS (USD $, component-consistent)
    # =========================================================================
    cost_rows = []
    for idx, row in enumerate(cycles_clean_ref.itertuples(index=False)):
        cost_id = f"CST-{500001 + idx}"
        cid = row.Cycle_ID
        tt = row.Treatment_Type
        sp = row.Stimulation_Protocol
        tr_type = row.Transfer_Type
        n_emb = row.Number_of_Embryos
        p = pt_lookup[row.Patient_ID]

        # Consultation Cost ($380 - $980)
        consult = np.round(np.clip(rng.normal(610, 95), 350, 1050), 2)

        # Medication Cost ($1,100 - $6,900; lower in Mild Stim, higher in DOR/older/Agonist Long)
        if sp == "Mild / Minimal Stimulation":
            med_mean = 1850
        elif sp == "Flare-Up Protocol":
            med_mean = 4650
        elif sp == "GnRH Agonist Long":
            med_mean = 4250
        else:
            med_mean = 3850
        med_age_adj = 280 if p["AMH_Level"] < 1.1 else (-220 if p["AMH_Level"] > 4.0 else 0)
        med_cost = np.round(np.clip(rng.normal(med_mean + med_age_adj, 620), 950, 7400), 2)

        # Laboratory Cost ($2,400 - $7,800; higher for ICSI & PGT-A)
        lab_base = {
            "Conventional IVF": 3150,
            "Mild Stimulation IVF": 2950,
            "ICSI": 4250,
            "IVF + PGT-A": 6150,
        }[tt]
        lab_cost = np.round(np.clip(rng.normal(lab_base + 55 * min(n_emb, 8), 430), 2100, 8600), 2)

        # Procedure Cost ($1,900 - $5,300; lower if No Transfer)
        proc_base = 2450 if tr_type == "No Transfer" else (4150 if tr_type == "Frozen-Thawed Transfer" else 3750)
        proc_cost = np.round(np.clip(rng.normal(proc_base, 390), 1750, 5600), 2)

        # Additional Cost ($0 - $3,400: cryopreservation, biopsy, luteal support extras)
        add_base = 1350 if tt == "IVF + PGT-A" else (780 if tr_type == "Frozen-Thawed Transfer" else 420)
        if n_emb >= 3:
            add_base += 450  # surplus embryo vitrification
        add_cost = np.round(max(0.0, rng.normal(add_base, 340)), 2)

        total_cost = np.round(consult + med_cost + lab_cost + proc_cost + add_cost, 2)

        cost_rows.append({
            "Cost_ID": cost_id,
            "Cycle_ID": cid,
            "Consultation_Cost": consult,
            "Medication_Cost": med_cost,
            "Laboratory_Cost": lab_cost,
            "Procedure_Cost": proc_cost,
            "Additional_Cost": add_cost,
            "Total_Treatment_Cost": total_cost,
        })

    costs_clean_ref = pd.DataFrame(cost_rows)

    # =========================================================================
    # 6. INJECT CONTROLLED, REALISTIC DATA QUALITY IMPERFECTIONS INTO RAW CSVs
